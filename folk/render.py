"""folk render -- deterministic templating over a person file (docs/design/folk-render.md).

No LLM anywhere in this module (Decision 1): it is pure string templating
over person.show_person's parsed sections, and running it twice on
unchanged input must produce byte-identical output -- the same testability
bar journal.rebuild_index holds itself to.

v1 reads only the person file (Decision 3) -- no journal/index query, no
observed/stated/interpreted triples. --format soul is implemented (Decision
4); --format dream emits a machine-readable JSON description for the
dream-sequence pipeline (still Bedrock-only, same section-parsing input).
Other formats raise NotImplementedError for the CLI to report.

Both formats carry `## Appearance` (docs/design/appearance.md) -- durable
physical description, emitted from every collection without exception: there
is no per-collection gate, because which collection a figure lives in is
already the human's statement of what that figure is for (appearance.md
Decision 6).
"""

import json
from pathlib import Path

from . import locus
from . import person

SUPPORTED_FORMATS = frozenset({"soul", "dream"})


class UnknownCheckpoint(Exception):
    """Raised when --checkpoint names a checkpoint the person/Locus file
    doesn't have (docs/design/appearance-checkpoints.md Decision 4) -- a
    hard error naming the ref and listing the checkpoints that do exist,
    never a silent fall-back to the base: that would be a good render of the
    wrong thing, the failure class compile.py's `!` lines exist to prevent.
    """


def _select_appearance(info, checkpoint, ref):
    """Resolve which appearance applies for this render: the base section
    when checkpoint is None/"", the merged view (docs/design/
    appearance-checkpoints.md Decision 2) when a valid checkpoint name is
    given. Raises UnknownCheckpoint, naming ref and listing the checkpoints
    that do exist, when checkpoint doesn't match any `## Appearance: <name>`
    section in the file.
    """
    if not checkpoint:
        return info["appearance"]
    available = info["appearance_checkpoints"]
    if checkpoint not in available:
        names = ", ".join(available.keys()) if available else "(none)"
        raise UnknownCheckpoint(
            f"{ref}: no checkpoint '{checkpoint}' -- available: {names}"
        )
    return person.merge_appearance_checkpoint(info["appearance"], available[checkpoint])


def _humanize_predicate(rel):
    return rel.replace("_", " ").strip()


def _render_association_line(assoc):
    name = assoc["name"]
    rel = assoc.get("type") or ""
    if rel:
        return f"- {_humanize_predicate(rel)} {name}"
    return f"- {name}"


def _appearance_lines(appearance):
    """`## Appearance` as markdown/plain lines: one `- label: value` per
    labeled pair in file order, then the free-text note as its own line.
    Shared by render_soul and render_dream's readable form so the two can't
    disagree about how a brief looks.
    """
    lines = [f"- {item['label']}: {item['value']}" for item in appearance["labels"]]
    if appearance["note"]:
        lines.append(appearance["note"])
    return lines


def _render_media_line(item):
    ref = item["ref"]
    note = item.get("note") or ""
    if note:
        return f"- {ref} — {note}"
    return f"- {ref}"


def render_soul(fpath, checkpoint=None):
    """Render the person file at fpath as SOUL.md-style markdown.

    Section order (Decision 3 / Scope): name, bio, Archetype, Voice,
    Associations, Tags, Media, Defining moments -- empty sections omitted,
    never emitted as empty headers.

    `checkpoint` selects a named `## Appearance: <name>` state to merge over
    the base (docs/design/appearance-checkpoints.md Decision 4 -- the flag is
    format-agnostic, soul included); None/"" renders the base alone.
    """
    info = person.show_person(fpath)
    slug = fpath.stem
    appearance = _select_appearance(info, checkpoint, f"person:{slug}")

    lines = [
        f"<!-- generated by folk render --format soul from person:{slug} "
        "— do not hand-edit; edit the person file and re-render -->",
        "",
        f"# {info['name']}",
    ]

    if info["bio"]:
        lines.append("")
        lines.append(info["bio"])

    if info["archetype"]:
        lines.append("")
        lines.append("## Archetype")
        lines.append(info["archetype"])

    if info["voice"]:
        lines.append("")
        lines.append("## Voice")
        lines.append(info["voice"])

    appearance_lines = _appearance_lines(appearance)
    if appearance_lines:
        lines.append("")
        lines.append("## Appearance")
        lines.extend(appearance_lines)

    if info["associations"]:
        lines.append("")
        lines.append("## Associations")
        for a in info["associations"]:
            lines.append(_render_association_line(a))

    if info["tags"]:
        lines.append("")
        lines.append("## Tags")
        lines.append(" ".join(info["tags"]))

    if info["media"]:
        lines.append("")
        lines.append("## Media")
        for m in info["media"]:
            lines.append(_render_media_line(m))

    if info["defining_moments"]:
        lines.append("")
        lines.append("## Defining moments")
        for dm in info["defining_moments"]:
            lines.append(f"- {dm}")

    return "\n".join(lines) + "\n"


def _dream_association_strings(assocs):
    """Associations as flat strings -- show_person's shape: the `name`,
    with the `type` in parentheses when present (e.g. "Norwegian Wood
    (appears_in)").
    """
    strings = []
    for a in assocs:
        if a["type"]:
            strings.append(f"{a['name']} ({a['type']})")
        else:
            strings.append(a["name"])
    return strings


def _dream_description(info, is_locus=False):
    """The dream pipeline's authoritative `description` field.

    For a person: bio, then "Archetype: ..." and "Voice: ..." blocks when
    non-empty. For a Locus: bio, then "Genius Loci: ..." when non-empty.
    Non-empty blocks are joined with a single blank line; empty blocks are
    omitted, never emitted as empty text.
    """
    blocks = []
    if info["bio"]:
        blocks.append(info["bio"])
    if is_locus:
        genius_loci = person._parse_free_text(info["sections"], "genius loci")
        if genius_loci:
            blocks.append(f"Genius Loci: {genius_loci}")
    else:
        if info["archetype"]:
            blocks.append(f"Archetype: {info['archetype']}")
        if info["voice"]:
            blocks.append(f"Voice: {info['voice']}")
    return "\n\n".join(blocks)


def _dream_descriptor(fpath, is_locus=False, checkpoint=None):
    """The dream JSON object for the person/Locus at fpath, in the
    contract's stable key order.

    `checkpoint` selects a named `## Appearance: <name>` state (docs/design/
    appearance-checkpoints.md Decision 4); None/"" is the base section alone.
    """
    info = locus.show_locus(fpath) if is_locus else person.show_person(fpath)
    ref = f"{'locus' if is_locus else 'person'}:{fpath.stem}"
    appearance = _select_appearance(info, checkpoint, ref)
    descriptor = {
        "kind": "locus" if is_locus else "person",
        "slug": fpath.stem,
        "name": info["name"],
        "description": _dream_description(info, is_locus=is_locus),
        # Appearance is a *sibling* of description, never folded into it
        # (Decision 4): description stays bio + Archetype/Voice, so every
        # consumer that predates this keeps working byte-for-byte and nothing
        # double-prints. All three are [] / "" when the section is absent --
        # never null, and never an error: a figure with no described shell is
        # the normal case, not a broken record.
        "appearance": appearance["labels"],
        "appearance_text": person.appearance_text(appearance),
        "appearance_fingerprint": person.appearance_fingerprint(appearance),
        # docs/design/appearance-checkpoints.md Decision 4: `checkpoint` is
        # the selected name ("" when none), `checkpoints` is every name the
        # file has, in file order, always emitted so a consumer can enumerate
        # without a second subprocess. A figure with none emits "" / [] and
        # is otherwise byte-identical to pre-checkpoint output.
        "checkpoint": checkpoint or "",
        "checkpoints": list(info["appearance_checkpoints"].keys()),
        "tags": info["tags"],
        "associations": _dream_association_strings(info["associations"]),
    }
    if not is_locus:
        descriptor["defining_moments"] = info["defining_moments"]
    return descriptor


def render_dream(fpath, is_locus=False, checkpoint=None):
    """Render the readable form of --format dream: the `description` text
    (bio + Archetype/Voice for a person, bio + Genius Loci for a Locus),
    followed by an `Appearance:` block when the person file has one.
    Newline-terminated like render_soul.

    Deliberately *not* the same string as the JSON `description` field
    (Decision 4): the readable form is for a human checking what a figure
    looks like, the JSON field is a contract with a compiler, and folding
    appearance into the latter would make every existing consumer print it
    twice. The asymmetry is a choice on the record, not an oversight.

    `checkpoint` selects a named `## Appearance: <name>` state
    (appearance-checkpoints.md Decision 4); None/"" is the base alone.
    """
    info = locus.show_locus(fpath) if is_locus else person.show_person(fpath)
    ref = f"{'locus' if is_locus else 'person'}:{fpath.stem}"
    appearance = _select_appearance(info, checkpoint, ref)
    blocks = [_dream_description(info, is_locus=is_locus)]
    appearance_lines = _appearance_lines(appearance)
    if appearance_lines:
        blocks.append("\n".join(["Appearance:"] + appearance_lines))
    return "\n\n".join(b for b in blocks if b) + "\n"


def render_dream_json(fpath, is_locus=False, checkpoint=None):
    """Render the machine-readable form of --format dream: a JSON string
    describing the person/Locus at fpath, pretty-printed with indent=2 and
    stable key order (insertion order, not sorted). Deterministic on
    unchanged input.
    """
    return json.dumps(_dream_descriptor(fpath, is_locus=is_locus, checkpoint=checkpoint), indent=2) + "\n"


def render(fmt, fpath, out=None, is_locus=False, checkpoint=None):
    """Render fpath in the given format. Returns the rendered text.

    Writes to `out` (a path) when given; the caller is responsible for
    stdout when `out` is None (folk has no privileged default write
    target -- Decision 5). `is_locus` switches the dream description from
    the person shape (bio + Archetype/Voice) to the Locus shape (bio +
    Genius Loci); irrelevant for soul. `checkpoint` selects a named
    `## Appearance: <name>` state, for either format (appearance-
    checkpoints.md Decision 4).
    """
    if fmt == "soul":
        text = render_soul(fpath, checkpoint=checkpoint)
    elif fmt == "dream":
        text = render_dream(fpath, is_locus=is_locus, checkpoint=checkpoint)
    else:
        raise NotImplementedError(f"folk render --format {fmt} is not yet implemented")

    if out is not None:
        Path(out).write_text(text)
    return text
