def _write_md(path, heading, sections=None, bio=""):
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# {heading}", ""]
    if bio:
        lines.append(bio)
        lines.append("")
    for name, body_lines in (sections or {}).items():
        lines.append(f"## {name}")
        lines.extend(body_lines)
        lines.append("")
    path.write_text("\n".join(lines) + "\n")


