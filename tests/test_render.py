class TestRenderSoul(unittest.TestCase):

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def test_full_person_all_sections_present_in_stable_order(self):
        fpath = self.tmp / "t" / "toru-watanabe" / "toru-watanabe.md"
        _write_md(
            fpath, "Toru Watanabe",
            bio="Narrator and protagonist of Norwegian Wood.",
            sections={
                "Archetype": ["reluctant witness"],
                "Voice": ["measured, understated"],
                "Associations": ["- [Norwegian Wood](work:norwegian-wood) — appears_in"],
                "Tags": ["character"],
                "Media": ["- portrait.jpg — cover art"],
                "Defining moments": ["- Naoko's death"],
            },
        )
        text = render.render_soul(fpath)

        self.assertTrue(text.startswith(
            "<!-- generated by folk render --format soul from person:toru-watanabe "
            "— do not hand-edit; edit the person file and re-render -->"
        ))

        # stable order: name, bio, archetype, voice, associations, tags, media, defining moments
        order = [
            "# Toru Watanabe",
            "Narrator and protagonist of Norwegian Wood.",
            "## Archetype",
            "reluctant witness",
            "## Voice",
            "measured, understated",
            "## Associations",
            "appears in Norwegian Wood",
            "## Tags",
            "character",
            "## Media",
            "portrait.jpg",
            "## Defining moments",
            "Naoko's death",
        ]
        positions = [text.index(fragment) for fragment in order]
        self.assertEqual(positions, sorted(positions))

    def test_empty_sections_omitted_not_emitted_as_empty_headers(self):
        fpath = self.tmp / "j" / "jane-doe" / "jane-doe.md"
        _write_md(fpath, "Jane Doe", bio="Brief description.")
        text = render.render_soul(fpath)
        for heading in ("## Archetype", "## Voice", "## Associations", "## Tags", "## Media", "## Defining moments"):
            self.assertNotIn(heading, text)
        self.assertIn("# Jane Doe", text)
        self.assertIn("Brief description.", text)

    def test_deterministic_byte_identical_on_repeat_render(self):
        fpath = self.tmp / "j" / "jane-doe" / "jane-doe.md"
        _write_md(
            fpath, "Jane Doe", bio="Brief description.",
            sections={"Tags": ["mentor guide"]},
        )
        first = render.render_soul(fpath)
        second = render.render_soul(fpath)
        self.assertEqual(first, second)

    def test_out_path_writes_file(self):
        fpath = self.tmp / "j" / "jane-doe" / "jane-doe.md"
        _write_md(fpath, "Jane Doe", bio="Brief description.")
        out_path = self.tmp / "SOUL.md"
        text = render.render(("soul"), fpath, out=out_path)
        self.assertEqual(out_path.read_text(), text)


class TestRenderDream(unittest.TestCase):

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)

    def _person(self, slug, heading, **kwargs):
        fpath = self.tmp / slug[0] / slug / f"{slug}.md"
        _write_md(fpath, heading, **kwargs)
        return fpath

    def _locus(self, slug, heading, **kwargs):
        fpath = self.tmp / "loci" / slug / f"{slug}.md"
        _write_md(fpath, heading, **kwargs)
        return fpath

    def _dream_json(self, fpath, is_locus=False):
        return json.loads(render.render_dream_json(fpath, is_locus=is_locus))

    def test_person_dream_json_shape_and_description_order(self):
        fpath = self._person(
            "toru-watanabe", "Toru Watanabe",
            bio="Narrator and protagonist of Norwegian Wood.",
            sections={
                "Archetype": ["reluctant witness"],
                "Voice": ["measured, understated, first-person retrospective"],
                "Associations": ["- [Norwegian Wood](work:norwegian-wood) — appears_in"],
                "Tags": ["character"],
                "Defining moments": ["- Naoko's death"],
            },
        )
        data = self._dream_json(fpath)
        self.assertEqual(data["kind"], "person")
        self.assertEqual(data["slug"], "toru-watanabe")
        self.assertEqual(data["name"], "Toru Watanabe")
        self.assertEqual(
            data["description"],
            "Narrator and protagonist of Norwegian Wood.\n\n"
            "Archetype: reluctant witness\n\n"
            "Voice: measured, understated, first-person retrospective",
        )
        self.assertEqual(data["tags"], ["character"])
        self.assertEqual(data["associations"], ["Norwegian Wood (appears_in)"])
        self.assertEqual(data["defining_moments"], ["Naoko's death"])
        # docs/design/appearance.md Decision 4 added the three appearance keys
        # after `description`: additive, so `description` itself is unchanged
        # (asserted above) and a consumer that predates them keeps working.
        # appearance-checkpoints.md Decision 4 added `checkpoint`/`checkpoints`
        # right after them, same additive discipline.
        self.assertEqual(
            list(data.keys()),
            ["kind", "slug", "name", "description", "appearance", "appearance_text",
             "appearance_fingerprint", "checkpoint", "checkpoints", "tags", "associations",
             "defining_moments"],
        )
        self.assertEqual(data["checkpoint"], "")
        self.assertEqual(data["checkpoints"], [])

    def test_person_dream_empty_sections_omitted(self):
        fpath = self._person("jane-doe", "Jane Doe", bio="Brief description.")
        data = self._dream_json(fpath)
        self.assertEqual(data["description"], "Brief description.")
        self.assertNotIn("Archetype:", data["description"])
        self.assertNotIn("Voice:", data["description"])
        self.assertEqual(data["tags"], [])
        self.assertEqual(data["associations"], [])
        self.assertEqual(data["defining_moments"], [])

    def test_locus_dream_json_contains_genius_loci(self):
        fpath = self._locus(
            "the-long-beach", "The Long Beach",
            bio="A long, empty stretch of beach.",
            sections={
                "Genius Loci": ["The ocean is the subject here."],
                "Tags": ["dream locus beach"],
            },
        )
        data = self._dream_json(fpath, is_locus=True)
        self.assertEqual(data["kind"], "locus")
        self.assertEqual(data["slug"], "the-long-beach")
        self.assertEqual(data["name"], "The Long Beach")
        self.assertEqual(
            data["description"],
            "A long, empty stretch of beach.\n\nGenius Loci: The ocean is the subject here.",
        )
        self.assertEqual(data["tags"], ["dream", "locus", "beach"])
        self.assertNotIn("defining_moments", data)
        self.assertNotIn("Archetype:", data["description"])

    def test_dream_deterministic_byte_identical_on_repeat_render(self):
        fpath = self._person(
            "jane-doe", "Jane Doe", bio="Brief description.",
            sections={"Tags": ["mentor guide"]},
        )
        self.assertEqual(render.render_dream_json(fpath), render.render_dream_json(fpath))
        self.assertEqual(render.render_dream(fpath), render.render_dream(fpath))
        locus_path = self._locus(
            "the-long-beach", "The Long Beach",
            bio="A long, empty stretch of beach.",
            sections={"Genius Loci": ["The ocean is the subject here."]},
        )
        self.assertEqual(
            render.render_dream_json(locus_path, is_locus=True),
            render.render_dream_json(locus_path, is_locus=True),
        )

    def test_dream_json_matches_readable_description(self):
        fpath = self._person(
            "toru-watanabe", "Toru Watanabe",
            bio="Narrator and protagonist of Norwegian Wood.",
            sections={"Archetype": ["reluctant witness"]},
        )
        data = self._dream_json(fpath)
        self.assertEqual(render.render_dream(fpath).rstrip("\n"), data["description"])

    def test_locus_dream_readable_contains_genius_loci_block(self):
        fpath = self._locus(
            "the-long-beach", "The Long Beach",
            bio="A long, empty stretch of beach.",
            sections={"Genius Loci": ["The ocean is the subject here."]},
        )
        text = render.render_dream(fpath, is_locus=True)
        self.assertIn("A long, empty stretch of beach.", text)
        self.assertIn("Genius Loci: The ocean is the subject here.", text)


class TestAppearanceCheckpoints(unittest.TestCase):
    """docs/design/appearance-checkpoints.md exit criteria."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.fpath = self.tmp / "j" / "january-scaller" / "january-scaller.md"
        _write_md(
            self.fpath, "January Scaller",
            bio="A girl who finds doors.",
            sections={
                "Appearance": [
                    "- skin: coppery, an in-between sort of thing",
                    "- eyes: round and light, set wide",
                ],
                "Appearance: age 7": [
                    "- build: small for her age, sharp-elbowed",
                    "- eyes: wide with wonder, always finding the doors first",
                ],
                "Appearance: age 17": [
                    "- build: tall, restless, coiled to run",
                ],
            },
        )

    def test_show_lists_checkpoint_names(self):
        info = person.show_person(self.fpath)
        self.assertEqual(list(info["appearance_checkpoints"].keys()), ["age 7", "age 17"])

    def test_merge_overrides_shared_label_in_base_position_and_appends_new_one(self):
        info = person.show_person(self.fpath)
        merged = person.merge_appearance_checkpoint(
            info["appearance"], info["appearance_checkpoints"]["age 7"])
        self.assertEqual(
            [item["label"] for item in merged["labels"]], ["skin", "eyes", "build"])
        eyes = next(i for i in merged["labels"] if i["label"] == "eyes")
        self.assertEqual(eyes["value"], "wide with wonder, always finding the doors first")

    def test_no_checkpoint_is_base_only_not_a_merge(self):
        data = json.loads(render.render_dream_json(self.fpath))
        self.assertEqual(
            [item["label"] for item in data["appearance"]], ["skin", "eyes"])
        eyes = next(i for i in data["appearance"] if i["label"] == "eyes")
        self.assertEqual(eyes["value"], "round and light, set wide")
        self.assertEqual(data["checkpoint"], "")
        self.assertEqual(data["checkpoints"], ["age 7", "age 17"])

    def test_checkpoint_selects_merged_view_in_dream_json(self):
        data = json.loads(render.render_dream_json(self.fpath, checkpoint="age 7"))
        self.assertEqual(data["checkpoint"], "age 7")
        labels = {item["label"]: item["value"] for item in data["appearance"]}
        self.assertEqual(labels["skin"], "coppery, an in-between sort of thing")
        self.assertEqual(labels["build"], "small for her age, sharp-elbowed")
        self.assertEqual(labels["eyes"], "wide with wonder, always finding the doors first")

    def test_checkpoint_runs_are_byte_identical_and_fingerprint_differs_per_checkpoint(self):
        first = render.render_dream_json(self.fpath, checkpoint="age 7")
        second = render.render_dream_json(self.fpath, checkpoint="age 7")
        self.assertEqual(first, second)
        fp7 = json.loads(first)["appearance_fingerprint"]
        fp17 = json.loads(render.render_dream_json(self.fpath, checkpoint="age 17"))["appearance_fingerprint"]
        fp_base = json.loads(render.render_dream_json(self.fpath))["appearance_fingerprint"]
        self.assertEqual(len({fp7, fp17, fp_base}), 3)

    def test_unknown_checkpoint_raises_and_lists_available_names(self):
        with self.assertRaises(render.UnknownCheckpoint) as ctx:
            render.render_dream_json(self.fpath, checkpoint="age 40")
        message = str(ctx.exception)
        self.assertIn("person:january-scaller", message)
        self.assertIn("age 40", message)
        self.assertIn("age 7", message)
        self.assertIn("age 17", message)

    def test_checkpoint_flag_is_format_agnostic_soul_accepts_it_too(self):
        base = render.render_soul(self.fpath)
        checkpointed = render.render_soul(self.fpath, checkpoint="age 7")
        self.assertIn("skin: coppery", base)
        self.assertNotIn("build: small for her age", base)
        self.assertIn("build: small for her age", checkpointed)
        self.assertEqual(checkpointed, render.render_soul(self.fpath, checkpoint="age 7"))

    def test_worked_example_chapter_1_only(self):
        """The spec's own worked example: a reading ceiling of chapter 1
        means exactly one checkpoint exists, and rendering it produces
        exactly that one name in `checkpoints`."""
        fpath = self.tmp / "j" / "january-ch1" / "january-ch1.md"
        _write_md(
            fpath, "January Scaller",
            bio="A girl who finds doors.",
            sections={
                "Appearance": [
                    "- skin: coppery, \"an in-between sort of thing\" by the world's reckoning of her (ch. 1)",
                    "- eyes: round and light, set wide (ch. 1)",
                ],
                "Appearance: age 7": [
                    "- build: small for her age, sharp-elbowed (ch. 1)",
                    "- dress: chosen by Mr. Locke's money — good cloth, stiff, correct, never hers (ch. 1)",
                ],
            },
        )
        data = json.loads(render.render_dream_json(fpath, checkpoint="age 7"))
        self.assertEqual(data["checkpoints"], ["age 7"])
        self.assertEqual(data["checkpoint"], "age 7")
        labels = {item["label"]: item["value"] for item in data["appearance"]}
        self.assertEqual(set(labels), {"skin", "eyes", "build", "dress"})

    def test_no_checkpoint_sections_still_resolves_unchanged(self):
        bare = self.tmp / "b" / "bare-figure" / "bare-figure.md"
        _write_md(bare, "Bare Figure", bio="No checkpoints here.")
        data = json.loads(render.render_dream_json(bare))
        self.assertEqual(data["checkpoint"], "")
        self.assertEqual(data["checkpoints"], [])

    def test_cli_unknown_checkpoint_exits_nonzero(self):
        args = argparse.Namespace(
            name="january-scaller", format="dream", json=True, out=None,
            collection=None, dir=str(self.tmp), checkpoint="age 40",
        )
        buf = io.StringIO()
        with self.assertRaises(SystemExit) as ctx:
            with redirect_stdout(buf):
                cli.cmd_render(args)
        self.assertNotEqual(ctx.exception.code, 0)

    def test_show_cli_lists_checkpoint_names(self):
        args = argparse.Namespace(name="january-scaller", collection=None, dir=str(self.tmp))
        buf = io.StringIO()
        with redirect_stdout(buf):
            cli.cmd_show(args)
        out = buf.getvalue()
        self.assertIn("Appearance checkpoints: age 7, age 17", out)


